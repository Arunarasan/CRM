// Generates the Flyway migration that loads the JB Decor product catalog (jb-decor-catalog.csv)
// into the public website tables. Images are expected at <siteUrl>/catalog/<sku-lower>-NN.jpg —
// copy them into website/public/catalog with copy-catalog-images.ps1.
//
//   node scripts/catalog/generate-catalog-migration.mjs > backend/src/main/resources/db/migration/V96__jb_decor_product_catalog.sql
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SITE = 'https://jbdecorcdm.com/catalog/'
const here = dirname(fileURLToPath(import.meta.url))

const CATEGORIES = {
  'Netlon (Mosquito Nets)': { slug: 'netlon-mosquito-nets', icon: 'ShieldCheck' },
  'Curtains': { slug: 'curtains', icon: 'Blinds' },
  'Blinds': { slug: 'blinds', icon: 'Layers' },
  'Curtain Rods & Accessories': { slug: 'curtain-rods-accessories', icon: 'Wrench' },
  'Mats & Flooring': { slug: 'mats-flooring', icon: 'Palette' },
  'Wall Decor': { slug: 'wall-decor', icon: 'Wallpaper' },
  'Interior Works': { slug: 'interior-works', icon: 'CookingPot' },
  'Home Decor': { slug: 'home-decor', icon: 'Flower2' },
}
const SERVICE_ICONS = { 'SRV-MEASURE': 'PencilRuler', 'SRV-STITCH': 'Gem', 'SRV-INSTALL': 'Wrench' }
const FEATURED = new Set(['NET-DOOR', 'CUR-CUSTOM', 'BL-ZEBRA', 'BL-WOODEN', 'ROD-FINIAL', 'WALL-FLUTED', 'INT-KITCHEN', 'INT-WARDROBE'])

function parseCsv(text) {
  const rows = []
  for (const line of text.split(/\r?\n/).filter(Boolean)) {
    const cells = []
    let cur = '', q = false
    for (let i = 0; i < line.length; i++) {
      const ch = line[i]
      if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++ } else if (ch === '"') q = false; else cur += ch }
      else if (ch === '"') q = true
      else if (ch === ',') { cells.push(cur); cur = '' }
      else cur += ch
    }
    cells.push(cur)
    rows.push(cells)
  }
  return rows.slice(1).map(([sku, name, category, unit, description, count]) =>
    ({ sku, name, category, unit, description, count: Number(count) }))
}

const slugify = (s) => s.toLowerCase().replace(/&/g, ' ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const sql = (v) => v == null ? 'NULL' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
const images = (r) => Array.from({ length: r.count }, (_, i) => `${SITE}${r.sku.toLowerCase()}-${String(i + 1).padStart(2, '0')}.jpg`)
const shortDesc = (d) => (d.length <= 160 ? d : d.slice(0, d.indexOf('.') + 1 || 160))

const rows = parseCsv(readFileSync(join(here, 'jb-decor-catalog.csv'), 'utf8'))
const out = []
out.push(`-- JB Decor real product catalog (${rows.length} rows from scripts/catalog/jb-decor-catalog.csv).
-- GENERATED by scripts/catalog/generate-catalog-migration.mjs — edit the CSV and regenerate, don't hand-edit.
-- Additive + idempotent: every insert is skipped when the slug already exists, so content later edited
-- from the CRM Website module is never overwritten. Images live at ${SITE}<sku>-NN.jpg
-- (website/public/catalog). Prices stay 0 — the public site is enquiry-only and never shows them.
`)

out.push('-- ── Categories ──')
Object.entries(CATEGORIES).forEach(([name, c], i) => {
  out.push(`INSERT INTO shop_categories (created_at, updated_at, created_by, version, is_deleted, name, slug, icon, display_order, active)
SELECT NOW(6), NOW(6), 'catalog-import', 0, b'0', ${sql(name)}, ${sql(c.slug)}, ${sql(c.icon)}, ${i + 1}, b'1'
FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM shop_categories WHERE slug = ${sql(c.slug)});`)
})

out.push('\n-- ── Products ──')
for (const r of rows.filter((r) => r.category !== 'Services')) {
  const cat = CATEGORIES[r.category]
  if (!cat) throw new Error(`Unknown category ${r.category} (${r.sku})`)
  const imgs = images(r)
  const slug = slugify(r.name)
  const specs = JSON.stringify([
    { label: 'Category', value: r.category },
    { label: 'Sold by', value: r.unit },
    { label: 'Product code', value: r.sku },
  ])
  out.push(`INSERT INTO shop_products (created_at, updated_at, created_by, version, is_deleted, name, slug, sku, category_id,
  short_description, description, image_url, gallery_json, specifications_json, price, stock, rating, review_count, featured, active)
SELECT NOW(6), NOW(6), 'catalog-import', 0, b'0', ${sql(r.name)}, ${sql(slug)}, ${sql(r.sku)},
  (SELECT id FROM shop_categories WHERE slug = ${sql(cat.slug)} AND is_deleted = b'0' LIMIT 1),
  ${sql(shortDesc(r.description))}, ${sql(r.description)}, ${sql(imgs[0] ?? null)}, ${sql(imgs.length ? JSON.stringify(imgs) : null)},
  ${sql(specs)}, 0, 0, 0, 0, ${FEATURED.has(r.sku) ? "b'1'" : "b'0'"}, b'1'
FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM shop_products WHERE slug = ${sql(slug)});`)
}

out.push('\n-- ── Services ──')
rows.filter((r) => r.category === 'Services').forEach((r, i) => {
  const slug = slugify(r.name)
  out.push(`INSERT INTO services (created_at, updated_at, created_by, version, is_deleted, title, slug, short_description, overview, image_url, icon, active, display_order)
SELECT NOW(6), NOW(6), 'catalog-import', 0, b'0', ${sql(r.name)}, ${sql(slug)}, ${sql(r.description)}, ${sql(r.description)},
  ${sql(images(r)[0] ?? null)}, ${sql(SERVICE_ICONS[r.sku] ?? 'Sparkles')}, b'1', ${i + 1}
FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM services WHERE slug = ${sql(slug)});`)
})

process.stdout.write(out.join('\n') + '\n')

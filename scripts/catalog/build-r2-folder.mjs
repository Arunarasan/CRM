// Re-arranges the website-ready JB Decor photos into the folder layout uploaded to Cloudflare R2:
//
//   <out>/catalog/<category-slug>/<product-slug>/<sku>-NN.jpg      (products)
//   <out>/catalog/services/<service-slug>/<sku>-NN.jpg             (SRV-* rows)
//
// Upload the CONTENTS of <out> to the bucket root so the keys start with "catalog/".
//
//   node scripts/catalog/build-r2-folder.mjs [sourceDir] [outDir]
//   node scripts/catalog/build-r2-folder.mjs --migration https://cdn.example.com > backend/src/main/resources/db/migration/V99__catalog_images_r2.sql
//
// The --migration form prints SQL that repoints shop_products.image_url/gallery_json and
// services.image_url at <base>/catalog/... (same paths this script writes).
import { readFileSync, mkdirSync, copyFileSync, existsSync, writeFileSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..')

const CATEGORY_SLUGS = {
  'Netlon (Mosquito Nets)': 'netlon-mosquito-nets',
  'Curtains': 'curtains',
  'Blinds': 'blinds',
  'Curtain Rods & Accessories': 'curtain-rods-accessories',
  'Mats & Flooring': 'mats-flooring',
  'Wall Decor': 'wall-decor',
  'Interior Works': 'interior-works',
  'Home Decor': 'home-decor',
}

function parseCsv(text) {
  const rows = []
  for (const line of text.replace(/^﻿/, '').split(/\r?\n/).filter(Boolean)) {
    const cells = []
    let cur = '', q = false
    for (let i = 0; i < line.length; i++) {
      const ch = line[i]
      if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++ } else if (ch === '"') q = false; else cur += ch }
      else if (ch === '"') q = true
      else if (ch === ',') { cells.push(cur); cur = '' }
      else cur += ch
    }
    cells.push(cur)
    rows.push(cells)
  }
  return rows.slice(1).map(([sku, name, category, , , count, images]) =>
    ({ sku, name, category, count: Number(count), images: (images ?? '').split(';').map((s) => s.trim()).filter(Boolean) }))
}

const slugify = (s) => s.toLowerCase().replace(/&/g, ' ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const sql = (v) => `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
const isService = (r) => r.sku.startsWith('SRV-')
const folderOf = (r) => isService(r)
  ? `catalog/services/${slugify(r.name)}`
  : `catalog/${CATEGORY_SLUGS[r.category] ?? slugify(r.category)}/${slugify(r.name)}`
const keysOf = (r) => Array.from({ length: r.count }, (_, i) =>
  `${folderOf(r)}/${r.sku.toLowerCase()}-${String(i + 1).padStart(2, '0')}.jpg`)

const args = process.argv.slice(2)
const migrationBase = args[0] === '--migration' ? args[1]?.replace(/\/+$/, '') : null
const source = (!migrationBase && args[0]) || join(root, 'jb', 'my product', 'website-ready')
const rows = parseCsv(readFileSync(join(source, 'products.csv'), 'utf8'))

if (migrationBase) {
  const out = [`-- Repoint the JB Decor catalog images (V96) at Cloudflare R2: ${migrationBase}/catalog/<category>/<product>/<sku>-NN.jpg
-- GENERATED by scripts/catalog/build-r2-folder.mjs --migration. Only touches rows still on the V96 URLs,
-- so images replaced later from the CRM Website module are left alone.`]
  for (const r of rows) {
    const urls = keysOf(r).map((k) => `${migrationBase}/${k}`)
    if (!urls.length) continue
    if (isService(r)) {
      out.push(`UPDATE services SET image_url = ${sql(urls[0])}
WHERE slug = ${sql(slugify(r.name))} AND image_url LIKE 'https://jbdecorcdm.com/catalog/%';`)
    } else {
      out.push(`UPDATE shop_products SET image_url = ${sql(urls[0])}, gallery_json = ${sql(JSON.stringify(urls))}
WHERE sku = ${sql(r.sku)} AND image_url LIKE 'https://jbdecorcdm.com/catalog/%';`)
    }
  }
  console.log(out.join('\n\n') + '\n')
} else {
  const outDir = args[1] || join(root, 'jb')
  rmSync(join(outDir, 'catalog'), { recursive: true, force: true })
  const manifest = ['sku,product,key']
  const missing = []
  let copied = 0
  for (const r of rows) {
    keysOf(r).forEach((key, i) => {
      const src = r.images[i] ? join(source, r.images[i]) : null
      if (!src || !existsSync(src)) { missing.push(`${r.sku} #${i + 1} (${r.images[i] ?? 'not listed'})`); return }
      mkdirSync(dirname(join(outDir, key)), { recursive: true })
      copyFileSync(src, join(outDir, key))
      manifest.push(`${r.sku},"${r.name.replace(/"/g, '""')}",${key}`)
      copied++
    })
  }
  writeFileSync(join(outDir, 'manifest.csv'), manifest.join('\n') + '\n')
  console.log(`Copied ${copied} images into ${join(outDir, 'catalog')}`)
  if (missing.length) { console.warn(`Missing ${missing.length}:\n  ${missing.join('\n  ')}`); process.exitCode = 1 }
}
